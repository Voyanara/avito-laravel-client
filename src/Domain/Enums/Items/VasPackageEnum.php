<?php

namespace Voyanara\LaravelApiClient\Domain\Enums\Items;

/**
 * Пакет дополнительных услуг для устаревшего метода применения пакета (putItemVasPackageV2).
 *
 * Пакеты x15_* и x20_* доступны только в некоторых регионах и категориях:
 * если применить их там, где они недоступны, оплата не пройдёт.
 *
 * @link https://support.avito.ru/articles/1398
 */
enum VasPackageEnum: string
{
    /** До 2 раз больше просмотров на 1 день */
    case X2_1 = 'x2_1';

    /** До 2 раз больше просмотров на 7 дней */
    case X2_7 = 'x2_7';

    /** До 5 раз больше просмотров на 1 день */
    case X5_1 = 'x5_1';

    /** До 5 раз больше просмотров на 7 дней */
    case X5_7 = 'x5_7';

    /** До 10 раз больше просмотров на 1 день */
    case X10_1 = 'x10_1';

    /** До 10 раз больше просмотров на 7 дней */
    case X10_7 = 'x10_7';

    /** До 15 раз больше просмотров на 1 день */
    case X15_1 = 'x15_1';

    /** До 15 раз больше просмотров на 7 дней */
    case X15_7 = 'x15_7';

    /** До 20 раз больше просмотров на 1 день */
    case X20_1 = 'x20_1';

    /** До 20 раз больше просмотров на 7 дней */
    case X20_7 = 'x20_7';
}
